/* ===== 会話の「組み合わせ」データ(会いに行く / デート) =====
   台詞を「場面 + セリフ + 余韻」の部品に分けて、ゲームが毎回ランダムに組み合わせて会話を作るためのファイルです。
   部品が 場面15 × セリフ20 × 余韻12 なら、1つの段階だけで 3600通り以上。同じ会話がほぼ続きません。
   (しくみは meet.js の meetMix / dateTalk。直前に出たものは避けて選びます)

   ■ このファイルに入っているもの
     MEET_MIX   …… 会いに行くの部品。段階ごとに { open:[場面], say:[セリフ], end:[余韻] }
                    talk=会話(好感度30〜) / touch=スキンシップ(50〜) / heart=打ち明け話(70〜) / melo=メロメロ(90〜)
     DATE_TALK  …… デート中の会話。好感度で low(〜49) / mid(50〜69) / high(70〜) に分かれます
     MEET_MIX_P / DATE_TALK_P …… 組み合わせ会話が選ばれる確率(0〜1)。残りは meet_lines.js / meet_girl.js / meet_scenes.js から選ばれます

   ■ 書き方
     ・1つの部品 = 1つの文字列。\n で改行すると、ノベルでは1行ずつ進みます。
     ・使える記号: {n}=その女子の名前 / {K}=柏木くん / {P}=フルネーム / {G}=名 / {school}=学園名
     ・open(場面)は、地の文で「{n}が現れた・近くにいた」ところまでを書きます。セリフは入れないでください(say と重なるため)。
     ・say(セリフ)は、「」で始めてください(その子のセリフとして表示されます)。2行目に（心の声）を足してもOK。
       どの場面の後ろに付いても違和感がないよう、場所や動作(「今、座ってるね」など)に触れないのがコツです。
     ・end(余韻)は、地の文か（心の声）。どの say の後ろでも自然な、さりげない1行にしてください。
     ・好きなだけ足せます。部品を1つ足すと、組み合わせが一気に増えます。
     ・※ 好感度が低くても、女子は全員{K}に興味津々で、最初から緊張しています。年齢相応のやさしい雰囲気で
       (手をつなぐ・寄りかかる・ハグまで)。傷つく言い方(「親しくないから」など)は書かないでください。
   ■ よくある書き間違い: 各部品の最後の「,」の抜け / ' の中の ' (' を使いたいときは " で囲むか、「」を使う) / ] の閉じ忘れ。 */

